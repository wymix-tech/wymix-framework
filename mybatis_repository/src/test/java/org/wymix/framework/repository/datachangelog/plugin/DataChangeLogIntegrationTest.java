package org.wymix.framework.repository.datachangelog.plugin;

import static org.junit.jupiter.api.Assertions.*;

import com.baomidou.mybatisplus.annotation.*;

import org.apache.ibatis.annotations.*;
import org.apache.ibatis.mapping.Environment;
import org.apache.ibatis.session.*;
import org.apache.ibatis.transaction.jdbc.JdbcTransactionFactory;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.*;
import org.springframework.context.ApplicationEventPublisher;
import org.springframework.test.util.ReflectionTestUtils;
import org.wymix.framework.repository.datachangelog.annotation.DataChangeLog;
import org.wymix.framework.repository.datachangelog.dto.DataChangeLogDTO;
import org.wymix.framework.repository.datachangelog.event.DataChangeLogEvent;

import java.util.*;

class DataChangeLogIntegrationTest {
    @TableName("review_orders")
    @DataChangeLog
    public static class Order {
        @TableId(value = "id", type = IdType.AUTO)
        public Long id;

        public String note;

        public Order(String note) {
            this.note = note;
        }
    }

    interface OrderMapper {
        @Insert("insert into review_orders(note) values(#{note})")
        @Options(useGeneratedKeys = true, keyProperty = "id")
        int insert(Order order);

        @Update("update review_orders set note=#{note} where id=#{id}")
        int update(Order order);

        @Delete("delete from review_orders where id=#{id}")
        int delete(long id);

        @Insert("insert into untracked(note) values(#{note})")
        int untracked(String note);
    }

    final List<DataChangeLogDTO> events = new ArrayList<>();
    SqlSessionFactory factory;

    @BeforeEach
    @SuppressWarnings("unchecked")
    void setup() throws Exception {
        JdbcDataSource ds = new JdbcDataSource();
        ds.setURL("jdbc:h2:mem:" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1");
        try (var connection = ds.getConnection();
                var statement = connection.createStatement()) {
            statement.execute(
                    "create table review_orders(id bigint generated by default as identity primary"
                            + " key, note varchar(30) unique)");
            statement.execute("create table untracked(note varchar(30))");
        }
        Configuration configuration =
                new Configuration(new Environment("test", new JdbcTransactionFactory(), ds));
        DataChangeLogPlugin plugin = new DataChangeLogPlugin();
        ReflectionTestUtils.setField(
                plugin,
                "applicationEventPublisher",
                (ApplicationEventPublisher)
                        event -> events.add(((DataChangeLogEvent) event).getDataChangeLogDTO()));
        configuration.addInterceptor(plugin);
        configuration.addMapper(OrderMapper.class);
        ((Map<String, Class<?>>)
                        ReflectionTestUtils.getField(DataChangeLogTableRegistry.class, "TABLES"))
                .put("review_orders", Order.class);
        factory = new SqlSessionFactoryBuilder().build(configuration);
    }

    @AfterEach
    @SuppressWarnings("unchecked")
    void cleanup() {
        ((Map<String, Class<?>>)
                        ReflectionTestUtils.getField(DataChangeLogTableRegistry.class, "TABLES"))
                .remove("review_orders");
    }

    @Test
    void publishesOnlyCommittedChangesIncludingNullTransitionsAndDelete() {
        try (SqlSession session = factory.openSession(false)) {
            Order order = new Order(null);
            var mapper = session.getMapper(OrderMapper.class);
            mapper.insert(order);
            assertNotNull(order.id);
            assertTrue(events.isEmpty());
            session.commit();
            assertEquals(1, events.size());
            assertEquals(order.id, events.get(0).getId());
            assertNull(events.get(0).getUri());
            events.clear();
            order.note = "changed";
            mapper.update(order);
            assertTrue(events.isEmpty());
            session.commit();
            assertEquals(1, events.size());
            assertTrue(
                    events.get(0).getFieldInfos().stream()
                            .anyMatch(
                                    f ->
                                            f.getOldValue() == null
                                                    && "changed".equals(f.getNewValue())));
            events.clear();
            mapper.delete(order.id);
            session.commit();
            assertEquals(1, events.size());
        }
    }

    @Test
    void rollbackFailureAndZeroRowsNeverPublish() {
        try (SqlSession session = factory.openSession(false)) {
            var mapper = session.getMapper(OrderMapper.class);
            mapper.insert(new Order("rollback"));
            session.rollback();
            assertTrue(events.isEmpty());
            Order absent = new Order("none");
            absent.id = 999L;
            assertEquals(0, mapper.update(absent));
            session.commit();
            assertTrue(events.isEmpty());
            mapper.insert(new Order("unique"));
            session.commit();
            events.clear();
            assertThrows(RuntimeException.class, () -> mapper.insert(new Order("unique")));
            session.rollback();
            assertTrue(events.isEmpty());
            mapper.untracked("allowed");
            session.commit();
            assertTrue(events.isEmpty());
        }
    }

    @Test
    void batchUsesActualUpdateCountsAndDoesNotPublishBeforeCommit() {
        try (SqlSession session = factory.openSession(ExecutorType.BATCH, false)) {
            var mapper = session.getMapper(OrderMapper.class);
            Order one = new Order("one"), two = new Order("two");
            mapper.insert(one);
            mapper.insert(two);
            assertTrue(events.isEmpty());
            session.flushStatements();
            assertTrue(events.isEmpty());
            session.commit();
            assertEquals(2, events.size());
            events.clear();
            Order absent = new Order("absent");
            absent.id = 999L;
            mapper.update(absent);
            session.commit();
            assertTrue(events.isEmpty());
            mapper.insert(new Order("discard"));
            session.rollback();
            assertTrue(events.isEmpty());
        }
    }

    @Test
    void autoCommitPublishesAfterSuccessfulExecution() {
        try (SqlSession session = factory.openSession(true)) {
            session.getMapper(OrderMapper.class).insert(new Order("immediate"));
            assertEquals(1, events.size());
        }
    }

    @Test
    void springTransactionPublishesOnlyAfterCommitAndDropsRollback() {
        var configuration = factory.getConfiguration();
        var ds = configuration.getEnvironment().getDataSource();
        configuration.setEnvironment(
                new Environment(
                        "spring",
                        new org.mybatis.spring.transaction.SpringManagedTransactionFactory(),
                        ds));
        var session = new org.mybatis.spring.SqlSessionTemplate(factory);
        var transactions =
                new org.springframework.transaction.support.TransactionTemplate(
                        new org.springframework.jdbc.datasource.DataSourceTransactionManager(ds));
        transactions.executeWithoutResult(
                status -> {
                    session.getMapper(OrderMapper.class).insert(new Order("spring-commit"));
                    assertTrue(events.isEmpty());
                });
        assertEquals(1, events.size());
        events.clear();
        transactions.executeWithoutResult(
                status -> {
                    session.getMapper(OrderMapper.class).insert(new Order("spring-rollback"));
                    status.setRollbackOnly();
                });
        assertTrue(events.isEmpty());
    }

    public static class Permission
            implements org.wymix.framework.repository.datapermission.inject.PermissionSqlInjector {
        public Map<String, Object> additionalParameters() {
            return java.util.Collections.singletonMap("excluded", "keep");
        }

        public String injectSql() {
            return "note != :excluded";
        }

        public org.wymix.framework.repository.datapermission.enums.InjectType type() {
            return org.wymix.framework.repository.datapermission.enums.InjectType.WHERE_ADDITIONAL;
        }
    }

    @Test
    void permissionNamedParametersPreserveGeneratedIdsAndNarrowAuditRows() {
        factory.getConfiguration()
                .addInterceptor(
                        new org.wymix.framework.repository.datapermission.plugin
                                .DataPermissionPlugin());
        var context =
                new org.wymix.framework.repository.datapermission.context
                        .DataPermissionContextHolder.DataPermissionContext();
        context.setStatementIds(new String[] {"ALL"});
        context.setInjectors(new java.util.ArrayList<>(List.of(Permission.class)));
        org.wymix.framework.repository.datapermission.context.DataPermissionContextHolder.mark(
                context);
        try (SqlSession session = factory.openSession(false)) {
            var mapper = session.getMapper(OrderMapper.class);
            Order keep = new Order("keep"), remove = new Order("remove");
            mapper.insert(keep);
            mapper.insert(remove);
            session.commit();
            assertNotNull(keep.id);
            assertNotNull(remove.id);
            events.clear();
            assertEquals(0, mapper.delete(keep.id));
            assertEquals(1, mapper.delete(remove.id));
            session.commit();
            assertEquals(1, events.size());
            assertEquals(remove.id, events.get(0).getId());
        } finally {
            org.wymix.framework.repository.datapermission.context.DataPermissionContextHolder
                    .clear();
        }
    }

    @Test
    void rejectsAutoCommitBatchBeforeEnqueuingWrites() {
        try (SqlSession session = factory.openSession(ExecutorType.BATCH, true)) {
            assertThrows(
                    RuntimeException.class,
                    () -> session.getMapper(OrderMapper.class).insert(new Order("unsafe")));
            assertTrue(session.flushStatements().isEmpty());
            assertTrue(events.isEmpty());
        }
    }
}
